import { cleanup, render, screen, within } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router";
import { afterEach, describe, expect, it, vi } from "vitest";
import summary from "../../../docs/api/examples/incident-summary.json";
import type { AnalysisReport } from "../api/contracts";
import { jsonResponse, mockFetch } from "../test/fetch";
import { AiReportPage } from "./AiReportPage";

// The panel on real model output, not on a hand-made example: the 18 reports the 27B model wrote
// in AI1 run 12 (prompt v2, docs/ai1-runs/12-*/reports). They are masked (host-01 ...), as the
// model wrote them; the report API un-masks them for display.
const RUN_12 = import.meta.glob<AnalysisReport>("../../../docs/ai1-runs/12-*/reports/*.json", {
  eager: true,
  import: "default",
});
const REPORTS = Object.entries(RUN_12).map(([path, report]) => [path.split("/").pop()!, report] as const);
const ID = summary.incident.incident_id;

afterEach(() => {
  cleanup();
  vi.restoreAllMocks();
});

function show(report: AnalysisReport) {
  mockFetch().mockImplementation(async (url) => {
    const path = String(url);
    if (path === `/api/incidents/${ID}`) return jsonResponse(summary);
    if (path === `/api/incidents/${ID}/report`) return jsonResponse({ ...report, incident_id: ID });
    return jsonResponse({ error: { code: "not_found", message: "No such path." } }, 404);
  });
  render(
    <MemoryRouter initialEntries={[`/incidents/${ID}/report`]}>
      <Routes>
        <Route path="/incidents/:incidentId/report" element={<AiReportPage />} />
      </Routes>
    </MemoryRouter>,
  );
}

describe("AiReportPage on the 27B run 12 reports", () => {
  it("has all 18 reports to test", () => {
    expect(REPORTS).toHaveLength(18);
  });

  it.each(REPORTS)("%s: every section, every finding and every cited event", async (_name, report) => {
    const errors = vi.spyOn(console, "error");
    show(report);
    const summaryBox = await screen.findByRole("region", { name: "Summary" });
    expect(summaryBox).toHaveTextContent(report.summary);

    const findings = screen.getByRole("region", { name: "Findings" });
    for (const finding of report.findings) expect(findings).toHaveTextContent(finding.statement);
    const steps = within(screen.getByRole("region", { name: "Attack sequence" })).queryAllByRole("listitem");
    expect(steps).toHaveLength(report.sequence?.length ?? 0);

    const cited = new Set([
      ...(report.sequence ?? []).flatMap((step) => step.cited_event_ids),
      ...report.findings.flatMap((finding) => finding.cited_event_ids),
    ]);
    const links = within(screen.getByRole("region", { name: "Cited evidence" })).queryAllByRole("link");
    expect(links.map((link) => link.textContent).sort()).toEqual([...cited].sort());

    const grounding = report.grounding!;
    const line = screen.getByText(
      new RegExp(`Grounding: ${grounding.grounded_factual_claims} of ${grounding.factual_claims} factual`),
    );
    expect(line.classList.contains("box--warn")).toBe(grounding.unsupported > 0);
    expect(screen.getByText(/Generated by hpc/)).toHaveTextContent(report.model_id!);
    // React reports duplicate keys and other render problems through console.error.
    expect(errors).not.toHaveBeenCalled();
  });
});
