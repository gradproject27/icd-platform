// npm run stub:build: writes dev/stub-data/incidents.json for the dev-only stub server. DEV AND
// TEST ONLY: src/ application code never imports it.
//
// Each stub incident joins two sources:
// - C3's correlation fixtures (fixtures/correlation): the incident's events with their role and
//   link_keys exactly as expected-incidents.json lists them, first/last event times (min/max
//   timestamp of those events in events.json) and the entities (sorted unique host, user,
//   src_ip and dst_ip of those events);
// - dev/stub-data/overlay.json (hand-written): status, incident type, analysis fields, times and
//   the risk block. The risk values are placeholders copied as they are; nothing here computes
//   a score (risk scoring belongs to C3).
//
// linked_at is not in the fixture, so the stub sets it to the incident's created_at. That is a
// stub-only stand-in, not a rule of the real system.
//
// The output is deterministic (LF, 2-space JSON, trailing newline), and a test rebuilds it in
// memory, so a fixture change without `npm run stub:build` fails the tests.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const FIXTURES_DIR = resolve(here, "../../fixtures/correlation");
export const OVERLAY_PATH = resolve(here, "stub-data/overlay.json");
export const OUTPUT_PATH = resolve(here, "stub-data/incidents.json");

const OVERLAY_FIELDS = [
  "status",
  "incident_type",
  "risk",
  "analysis_status",
  "analysis_attempts",
  "latest_report_id",
  "confidence",
  "created_at",
  "updated_at",
];

const sortedUnique = (values) => [...new Set(values.filter((value) => value !== null && value !== undefined))].sort();

/** Pure: the stub data from the parsed fixture files and overlay. */
export function buildStubData({ expected, events, overlay }) {
  const eventsById = new Map(events.map((event) => [event.event_id, event]));
  const fixtureByLabel = new Map(expected.incidents.map((incident) => [incident.label, incident]));

  const items = overlay.incidents.map((entry) => {
    const fixture = fixtureByLabel.get(entry.fixture_label);
    if (!fixture) throw new Error(`${entry.incident_id}: no fixture incident labelled ${entry.fixture_label}`);

    const links = [
      ...fixture.flagged.map((link) => ({ ...link, role: "flagged" })),
      ...fixture.context.map((link) => ({ ...link, role: "context" })),
    ];
    const linked = links.map(({ event_id }) => {
      const event = eventsById.get(event_id);
      if (!event) throw new Error(`${entry.incident_id}: event ${event_id} is not in events.json`);
      return event;
    });
    const times = linked.map((event) => event.timestamp).sort((a, b) => Date.parse(a) - Date.parse(b));

    const incident = {
      schema_version: "1.0",
      incident_id: entry.incident_id,
      created_at: entry.created_at,
      updated_at: entry.updated_at,
      first_event_at: times[0],
      last_event_at: times[times.length - 1],
      events: links.map(({ event_id, role, link_keys }) => ({
        event_id,
        role,
        link_keys,
        linked_at: entry.created_at,
      })),
    };
    for (const field of OVERLAY_FIELDS) {
      if (!(field in entry)) throw new Error(`${entry.incident_id}: overlay has no ${field}`);
      if (!(field in incident)) incident[field] = entry[field];
    }

    const entities = {
      hosts: sortedUnique(linked.map((event) => event.host)),
      users: sortedUnique(linked.map((event) => event.user)),
      ips: sortedUnique(linked.flatMap((event) => [event.src_ip, event.dst_ip])),
    };
    return { fixture_label: entry.fixture_label, incident, entities };
  });

  return {
    _comment:
      "GENERATED by dev/build-stub-incidents.mjs from fixtures/correlation and dev/stub-data/overlay.json. " +
      "DEV AND TEST ONLY: example data for the stub server; risk values are placeholders, not C3 results.",
    items,
  };
}

export async function readSources() {
  const read = async (path) => JSON.parse(await readFile(path, "utf8"));
  return {
    expected: await read(resolve(FIXTURES_DIR, "expected-incidents.json")),
    events: await read(resolve(FIXTURES_DIR, "events.json")),
    overlay: await read(OVERLAY_PATH),
  };
}

export const toText = (data) => `${JSON.stringify(data, null, 2)}\n`;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = buildStubData(await readSources());
  await writeFile(OUTPUT_PATH, toText(data), "utf8");
  console.log(`Wrote ${data.items.length} stub incidents to dev/stub-data/incidents.json.`);
}
